#!/usr/bin/env bash
# Creates the production .env with fresh random secrets. Run once in the app directory.
set -euo pipefail
cd "$(dirname "$0")/.."
if [ -f .env ]; then
  echo ".env existiert schon – nichts geändert. (Zum Neuanlegen erst löschen.)"
  exit 1
fi

ask() { local v; read -rp "$1: " v < /dev/tty; printf '%s' "$v"; }
domain=$(ask "Adresse der App (z. B. studio.needl-booker.de)")
admin_email=$(ask "Google-Adresse des Admins")
admin_name=$(ask "Name des Admins")
operator_email=$(ask "Google-Adresse des Betreibers (du, für Rechnungsdaten)")
google_id=$(ask "Google Client-ID")
google_secret=$(ask "Google Clientschlüssel")

rand64() { openssl rand -base64 32 | tr -d '\n'; }
randhex() { openssl rand -hex 32; }
db_password=$(randhex)

umask 077
cat > .env <<ENV
# Production configuration – generated by deploy/make-env.sh. Keep secret!
APP_DOMAIN="$domain"
APP_URL="https://$domain"
# Auth.js must know the public address (otherwise it sees the container-internal host)
AUTH_URL="https://$domain"
APP_TIMEZONE="Europe/Berlin"
PHONE_DEFAULT_COUNTRY="DE"

POSTGRES_USER="needl"
POSTGRES_DB="needl"
POSTGRES_PASSWORD="$db_password"
DATABASE_URL="postgresql://needl:$db_password@db:5432/needl"

AUTH_SECRET="$(rand64)"
AUTH_TRUST_HOST="true"
AUTH_GOOGLE_ID="$google_id"
AUTH_GOOGLE_SECRET="$google_secret"
GOOGLE_WORKSPACE_DOMAIN=""
ADMIN_EMAIL="$admin_email"
ADMIN_NAME="$admin_name"
DEV_LOGIN_ENABLED="false"

GOOGLE_CALENDAR_MOCK="false"
TOKEN_ENCRYPTION_KEY="$(rand64)"

# Not connected yet: sample/off until Meta, WhatsApp and TeamUp are set up
META_GRAPH_MOCK="true"
META_APP_SECRET="$(randhex)"
META_VERIFY_TOKEN="$(randhex)"
META_PAGE_ACCESS_TOKEN=""
META_GRAPH_API_VERSION="v23.0"
WHATSAPP_MOCK="true"
WHATSAPP_VERIFY_TOKEN="$(randhex)"
TEAMUP_MOCK="false"
TEAMUP_API_KEY=""
TEAMUP_CALENDAR_KEY=""
BOT_API_KEY=""
BOT_WEBHOOK_URL=""
BOT_WEBHOOK_SECRET=""
# Built-in WhatsApp bot (Claude). Set the key to switch it on; customer messages are
# then answered by NEEDL itself instead of being sent to BOT_WEBHOOK_URL.
ANTHROPIC_API_KEY=""
# Optional: model and effort (low | medium | high)
BOT_MODEL="claude-opus-5-5"
BOT_EFFORT="low"

# Commission invoices: details are maintained in the app (Einstellungen) by the operator
OPERATOR_EMAIL="$operator_email"
BILLING_COMMISSION_PERCENT="15"
BILLING_VAT_PERCENT="19"
BILLING_PAYMENT_DAYS="14"
BILLING_ISSUER_NAME=""
BILLING_ISSUER_ADDRESS=""
BILLING_ISSUER_TAX_ID=""
BILLING_ISSUER_IBAN=""
BILLING_ISSUER_EMAIL=""
ENV
echo
echo ".env angelegt (nur für root lesbar). Starten mit:"
echo "  bash deploy/update.sh"
